import type { ArticleDefinition } from "../article";
import { f2, g15 } from "../format";
import type { ArticleDraft } from "../types";

/** A built measurement within this of its POM reads OK in the report, as in the reference script. */
export const REPORT_TOLERANCE_MM = 0.5;

const header = (title: string, sizes: readonly string[]): string =>
  `| ${title} | ${sizes.join(" | ")} |\n|---|${sizes.map(() => "---").join("|")}|\n`;

function checkRows(drafts: readonly ArticleDraft[]): string {
  return drafts[0].checks
    .map((check, i) => {
      const cells = drafts.map((d) => {
        const { target, actual } = d.checks[i];
        return Math.abs(target - actual) < REPORT_TOLERANCE_MM ? `${f2(actual)} OK` : `${f2(actual)} CHECK (target ${f2(target)})`;
      });
      return `| ${check.label} | ${cells.join(" | ")} |\n`;
    })
    .join("");
}

function lengthRows(drafts: readonly ArticleDraft[]): string {
  return drafts[0].lengths.map((l, i) => `| ${l.label} | ${drafts.map((d) => f2(d.lengths[i].mm)).join(" | ")} |\n`).join("");
}

/** The parameters a draft differs from the defaults in, so a report says what it was drafted at. */
function inputLine(article: ArticleDefinition, draft: ArticleDraft): string {
  const changed = article.parameters.filter((p) => draft.input.parameters[p.key] !== p.default).map((p) => `${p.key} ${draft.input.parameters[p.key]} mm`);
  return changed.length === 0 ? "" : `Drafted with ${changed.join(", ")}.\n\n`;
}

/** `pattern/pattern-report.md`: the built measurements against the POM table, and the seam lengths that must agree. */
export function patternReport(article: ArticleDefinition, drafts: readonly ArticleDraft[]): string {
  const sizes = drafts.map((d) => d.size);
  const k = article.draft_constants;
  return [
    `# ${article.code} pattern report (v${article.version})\n\n`,
    "Generated by the Knitwright parametric drafter (`lib/parametric`, a port of `tools/draft-pattern.ps1`) from `article.json`. All values in mm.\n\n",
    inputLine(article, drafts[0]),
    "## Measurements built into the pattern vs the POM table\n\n",
    header("Check", sizes),
    checkRows(drafts),
    "\n## Seam lengths that must match\n\n",
    header("Length", sizes),
    lengthRows(drafts),
    `\nSleeve cap ease target: ${g15(k.sleeve_cap_ease_target[0])}-${g15(k.sleeve_cap_ease_target[1])} mm in total (knit fabric, set flat). Rib length = neckline x ${g15(k.rib_ratio)}.\n`,
  ].join("");
}
